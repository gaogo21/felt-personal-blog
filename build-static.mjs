import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync('dist/app.js', 'utf8').replace(/^import .*\n/, '');
const context = {document:{querySelector:()=>null, querySelectorAll:()=>[]}, matchMedia:()=>({matches:false})};
vm.createContext(context);
vm.runInContext(source.slice(0, source.indexOf('function setupExperience'))+';result=home();',context);
const page = fs.readFileSync('dist/index.html', 'utf8');
const fallback = context.result+'<noscript><p class="section-wrap">请启用 JavaScript 查看博客内容。</p></noscript>';
fs.writeFileSync('dist/index.html', page.replace(/(<main id="main" tabindex="-1">)[\s\S]*?(<\/main>)/, '$1'+fallback+'$2'));
console.log('Static hero synchronized; blog content loads from the public API.');
